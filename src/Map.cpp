Map::Map()
{
    BACKGROUND = TextureManager::loadTexture("Assets/Space.png");
    loadMap(level1);
    SRC_RECT.x = 0;
    SRC_RECT.y = 0;
    SRC_RECT.w = 32;
    SRC_RECT.h = 32;
    DEST_RECT.w = 32;
    DEST_RECT.h = 32;
    DEST_RECT.x = 0;
    DEST_RECT.y = 0;
}

void Map::loadMap(int arr[20][25])
{
    for (int r = 0; r < 20; r++)
    {
        for (int c = 0; c < 25; c++)
        {
            MAP[r][c] = arr[r][c];
        }
    }
}

void Map::drawMap()
{
    int type = 0;
    
    for (int r = 0; r < 20; r++)
    {
        for (int c = 0; c < 25; c++)
        {
            type = MAP[r][c];
            DEST_RECT.x = c * 32;
            DEST_RECT.y = r * 32;
            
            switch (type)
            {
                case 0:
                    TextureManager::draw(BACKGROUND, SRC_RECT, DEST_RECT);
                    break;
                case 1:
                    //draw something else TextureManager::draw(BACKGROUND, SRC_RECT, DEST_RECT);
                    break;
                case 2:
                    //draw something else TextureManager::draw(BACKGROUND, SRC_RECT, DEST_RECT);
                    break;
                default:
                    break;
            }
        }
    }
}
